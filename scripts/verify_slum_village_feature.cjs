const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const songs=JSON.parse(fs.readFileSync('tracks.json','utf8'));
const features=JSON.parse(fs.readFileSync('features.json','utf8')).features;
const f=features.find(x=>x.id==='slum-village');
assert(f&&features.filter(x=>x.id==='slum-village').length===1);
assert.deepEqual(f.names,['Slum Village']);assert.deepEqual(f.aliases,['J-88']);
assert.deepEqual(f.scopeOwnNames,['Slum Village','J-88']);
assert(f.allYears&&f.visual.precomposed&&f.visual.fit==='contain');
assert.equal(f.visual.provenance,'user-provided');assert(f.identityNote.includes('Detroit'));
const source=fs.readFileSync('src/app/editorial.js','utf8');
const helpers=source.split('\n').filter(line=>/^ function feature(?:Tracks|ScopeIdentity|Identity)\(/.test(line)).join('\n');
const ctx=vm.createContext({songs,yearSort:t=>t.year??9999});vm.runInContext(helpers,ctx);
const all=Array.from(ctx.featureTracks(f));
const own=all.filter(t=>ctx.featureScopeIdentity(f,t));
const related=all.filter(t=>!ctx.featureScopeIdentity(f,t));
assert.equal(all.length,18);assert.equal(own.length,15);assert.equal(related.length,3);
assert.deepEqual(related.map(t=>t.id).sort(),['common-thelonius','dj-jazzy-jeff-are-u-ready','dwele-angel-user-selected'].sort());
assert(own.some(t=>t.artist==='J-88'));
const built=JSON.parse(fs.readFileSync('.build-support/frontend.json','utf8')).features.find(x=>x.id==='slum-village');
assert.equal(built.qualification.artistCount,15);assert.deepEqual(built.qualification.artistIds.slice().sort(),own.map(t=>t.id).sort());
assert(all.every(t=>['Slum Village','J-88'].includes(t.artist)||(t.artists||[]).includes('Slum Village')));
for(const prior of features.filter(x=>x.id!=='slum-village'))for(const t of songs)assert.equal(ctx.featureScopeIdentity(prior,t),ctx.featureIdentity(prior,t));
assert(source.includes("scope==='own'?featureScopeIdentity(f,t):!featureScopeIdentity(f,t)"));
assert(source.includes('initialScope=false;scopePersonQueue(filtered);'));
const html=fs.readFileSync('dist/artists/slum-village.html','utf8');
for(const s of f.editorial.sections)assert(html.includes(s.heading));
for(const s of f.editorial.sources)assert(html.includes(s.url));
assert(html.includes('収録作品 18曲'));
assert(html.includes(f.visual.photo));assert(html.includes(f.visual.tag));
assert(html.includes('https://djnaoyaman.github.io/cratediggin/artists/slum-village.html'));
const meta=JSON.parse(fs.readFileSync('dist/metadata.js','utf8').replace(/^window.CRATE_PAGES=/,'').replace(/;\s*$/,''));
assert.equal(meta['#/feature/slum-village'].path,'/cratediggin/artists/slum-village.html');
assert(meta['#/feature/slum-village'].image.includes('/feature-og/slum-village.jpg'));
console.log('Slum Village feature: 18 unique related tracks / 15 own+alias / 3 guests; existing scopes unchanged; source, photo and metadata PASS');
